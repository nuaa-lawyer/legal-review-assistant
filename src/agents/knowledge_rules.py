MAX_MANDATORY_TOTAL = 12


def _dedupe(pairs: list) -> list:
    seen, out = set(), []
    for p in pairs:
        if p not in seen:
            seen.add(p)
            out.append(p)
    return out


def keyword_pairs(user_input: str) -> list:
    """根据功能描述中的关键词，返回应当强制召回的场景条款"""
    text = user_input or ""
    pairs = []
    for keywords, articles in KEYWORD_MANDATORY:
        if any(k in text for k in keywords):
            pairs.extend(articles)
    return _dedupe(pairs)


def mandatory_pairs(classification: dict, user_input: str = "") -> list:
    """
    返回需要强制召回的核心条款，优先级：
    行业专门法规 > 场景关键词规则 > 通用风险领域规则
    """
    pairs = []
    industry = classification.get("industry")
    if industry:
        pairs.extend(INDUSTRY_MANDATORY.get(industry, []))
    pairs.extend(keyword_pairs(user_input))
    for area in classification.get("risk_areas") or []:
        pairs.extend(MANDATORY_MAP.get(area, []))
    return _dedupe(pairs)[:MAX_MANDATORY_TOTAL]
